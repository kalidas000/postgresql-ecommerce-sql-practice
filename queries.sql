-- 1. Display all products
SELECT name, price, stock FROM products;

-- 2. Products above ₹2000
SELECT name, price
FROM products
WHERE price > 2000;



-- 3. Products containing "USB"
SELECT name, price
FROM products
WHERE name ILIKE '%usb%';


-- 4. Products with stock above 10
SELECT name, price, stock
FROM products
WHERE stock > 10
ORDER BY stock DESC;


-- 5. Out-of-stock products
SELECT *
FROM products
WHERE stock <= 0;


-- 6. Products with specific SKUs
SELECT name, sku, price
FROM products
WHERE sku IN ('WM-001', 'SSD-007', 'CH-008');


-- 7. Products within a price range
SELECT name, price
FROM products
WHERE price BETWEEN 1000 AND 3500;

-- 8. Average product price
SELECT ROUND(avg(price),2) AS average_price
FROM products;

-- 9. Number of products at each stock level
SELECT stock, COUNT(*) AS product_count
FROM products
GROUP BY stock
ORDER BY stock;

-- 10. Stock value of each product
SELECT name, stock, price as per_stock_price, price * stock as stock_value
FROM products
ORDER BY stock_value;

-- 11. Display orders with customer information
SELECT  u.name as customer_name, o.id as order_id, o.status
FROM orders as o
INNER JOIN users as u
ON o.user_id = u.id;

-- 12. Count order items per customer
SELECT u.name as customer_name, COUNT(oi.order_id) as indvidual_total_orders
FROM orders as o
INNER JOIN users as u
ON o.user_id = u.id
INNER JOIN order_items as oi
ON oi.order_id = o.id
INNER JOIN products as p
ON p.id = oi.product_id
GROUP BY u.name
ORDER BY indvidual_total_orders;

-- 13. Total spending of each customer
SELECT u.name as customer_name, SUM(p.price * oi.quantity) AS total_spent
FROM orders as o
INNER JOIN users as u
ON o.user_id = u.id
INNER JOIN order_items as oi
ON oi.order_id = o.id
INNER JOIN products as p
ON p.id = oi.product_id
GROUP BY u.name;

-- 14. Products priced above the average price
SELECT name, price
FROM products
WHERE price > (select avg(price) FROM products);

-- 15. Customers spending more than ₹5000
SELECT u.name as customer_name, SUM(p.price * oi.quantity) as total_expenditure
FROM users as u
INNER JOIN orders as o
ON u.id = o.user_id
INNER JOIN order_items as oi
ON oi.order_id = o.id
INNER JOIN products as p
ON p.id = oi.product_id
GROUP BY u.name
HAVING SUM(p.price * oi.quantity) > 5000
ORDER BY total_expenditure;


-- 16. Most-ordered product by quantity
