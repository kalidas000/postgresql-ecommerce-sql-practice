-- 20. Customers who placed more than one order
SELECT u.name, COUNT(o.id) AS total_orders
FROM users as u
INNER JOIN orders as o
ON u.id = o.user_id
GROUP BY u.name
HAVING count(o.id) > 1;


-- 21. Average order value for each customer
SELECT u.name as customer_name, ROUND(AVG(order_total), 2) as average_order_value
FROM (
    SELECT o.id AS order_id, SUM(p.price * oi.quantity) AS order_total
    FROM orders as o
    INNER JOIN order_items as oi
    ON oi.order_id = o.id
    INNER JOIN products as p
    ON p.id = oi.product_id
    GROUP BY o.id
) AS order_totals
INNER JOIN orders as o
ON order_totals.order_id = o.id
INNER JOIN users as u
ON u.id = o.user_id
GROUP BY u.name;

