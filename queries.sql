-- 27. Orders containing more than one different product
SELECT o.id as order_details, count(DISTINCT p.id) AS products_count
FROM order_items as oi
INNER JOIN products as p 
ON oi.product_id = p.id
INNER JOIN orders as o
ON o.id = oi.order_id
GROUP BY o.id
HAVING count(DISTINCT p.id) > 1;

-- 28. Customer who spent the most on a single order
SELECT u.name as customer_name, order_total
FROM (
    SELECT o.id as order_id, SUM(p.price * oi.quantity) AS order_total
    FROM users as u
    INNER JOIN orders as o
    ON u.id = o.user_id
    INNER JOIN order_items as oi
    ON oi.order_id = o.id
    INNER JOIN products as p
    ON p.id = oi.product_id
    GROUP BY o.id
    ORDER BY order_total DESC LIMIT 1
) AS order_totals
INNER JOIN orders as o
ON o.id = order_totals.order_id
INNER JOIN users as u
ON u.id = o.user_id;

-- 29. Products generating more revenue than the average product revenue
SELECT p.id as product_id, p.name as product_name, SUM(oi.quantity * p.price) as product_income_generated
FROM products as p
INNER JOIN order_items as oi
ON oi.product_id = p.id
GROUP BY p.name, p.id
HAVING SUM(oi.quantity * p.price) > 
    (SELECT ROUND(AVG(product_revenue), 2)
    FROM (
        SELECT p.id as product_id, SUM(p.price * oi.quantity) as product_revenue
        FROM order_items as oi
        INNER JOIN products as p
        ON p.id = oi.product_id
        GROUP BY p.id
    ) AS product_revenues
    );

-- 30. Each customer's most expensive order
SELECT order_totals.user_name as customer_name, order_totals.order_id, order_totals.order_total
FROM (
    -- find the total value of every order
    SELECT u.name AS user_name, o.id AS order_id, SUM(p.price * oi.quantity) as order_total
    FROM products AS p
    INNER JOIN order_items AS oi
    ON p.id = oi.product_id
    INNER JOIN orders as o
    ON o.id = oi.order_id
    INNER JOIN users as u
    ON u.id = o.user_id
    GROUP BY o.id, u.name
    ) AS order_totals

INNER JOIN (
    -- Find the total order price of the each customer
        SELECT order_totals.user_name, MAX(order_totals.order_total) AS max_of_orders
        FROM (
            SELECT u.name AS user_name, o.id AS order_id, SUM(p.price * oi.quantity) as order_total
            FROM products AS p
            INNER JOIN order_items AS oi
            ON p.id = oi.product_id
            INNER JOIN orders as o
            ON o.id = oi.order_id
            INNER JOIN users as u
            ON u.id = o.user_id
            GROUP BY o.id, u.name
    ) AS order_totals
    GROUP BY order_totals.user_name
) AS max_orders

ON order_totals.user_name = max_orders.user_name
AND order_totals.order_total = max_orders.max_of_orders;

